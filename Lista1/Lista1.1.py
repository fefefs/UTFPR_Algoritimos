'''1) Crie um algoritmo para ler, escrever e calcular a média aritmética entre a altura de duas
pessoas'''

pessoa1 = float(input("Digite a altura da pessoa 1: "))
pessoa2 = float(input("Digite a altura da pessoa 2: "))

print("\n Altura da pessoa 1 : ", pessoa1)
print("Altura da pessoa 2 : ", pessoa2)
print("Média das alturas :", (pessoa1 + pessoa2) / 2)